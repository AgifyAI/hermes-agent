"""The auxiliary-model judge (and the completion-contract drafter) as a shared side-LLM helper.

This is NOT part of the /goal decision path any more: a standing goal is ended by the agent itself
through the ``update_goal`` tool (see hermes_cli/goal_driver.py). The judge remains the optional
side-model check for features that ask an auxiliary model to grade text: ``/loop --until`` and the
kanban review gate, plus the ``/goal draft`` contract drafting call.
"""

